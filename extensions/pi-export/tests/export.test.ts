import assert from "node:assert/strict";
import { mkdtemp, readFile, readdir, rm, stat, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { test } from "node:test";
import { CURRENT_SESSION_VERSION, SessionManager, type ExtensionToolContext } from "@earendil-works/pi-coding-agent";
import { exportSession } from "../index.js";

test("exports the selected raw branch to JSONL and the saved tree to Pi HTML", async t => {
  const cwd = await mkdtemp(join(tmpdir(), "pi export 'fixture'-"));
  t.after(() => rm(cwd, { recursive: true, force: true }));
  // The standalone exporter reads bootstrap settings. Never point it at the user's home.
  const agentDir = process.env.PI_CODING_AGENT_DIR;
  process.env.PI_CODING_AGENT_DIR = join(cwd, "agent");
  t.after(() => { if (agentDir === undefined) delete process.env.PI_CODING_AGENT_DIR; else process.env.PI_CODING_AGENT_DIR = agentDir; });
  const timestamp = new Date(0).toISOString();
  const header = { type: "session", version: CURRENT_SESSION_VERSION, id: "fixture", cwd, timestamp, parentSession: "/private/source.jsonl" };
  const entries = [["root", null], ["active", "root"], ["abandoned", "root"]].map(([id, parentId]) => ({ type: "custom", id, parentId, timestamp, customType: "fixture", data: id }));
  const file = join(cwd, "input.jsonl");
  const source = [header, ...entries].map(line => JSON.stringify(line)).join("\n") + "\n";
  await writeFile(file, source);
  const sm = SessionManager.open(file, cwd);
  sm.branch("active");
  const run = (format: "html" | "jsonl", sessionManager = sm, signal?: AbortSignal) => exportSession.execute("call", { format }, signal, undefined, { sessionManager, cwd } as unknown as ExtensionToolContext);
  const [html, jsonl] = await Promise.all([run("html"), run("jsonl")]);
  const lines = (await readFile(jsonl.details.path, "utf8")).trimEnd().split("\n").map(line => JSON.parse(line));
  assert.deepEqual(lines.slice(1), entries.slice(0, 2));
  const { parentSession: _omitted, ...freshHeader } = header;
  assert.deepEqual(lines[0], { ...freshHeader, timestamp: lines[0].timestamp });
  assert.notEqual(lines[0].timestamp, timestamp);
  const viewer = await readFile(html.details.path, "utf8");
  const encoded = /<script id="session-data"[^>]*>([^<]+)<\/script>/.exec(viewer)?.[1];
  assert(encoded, "Pi viewer embeds session data");
  const tree = JSON.parse(Buffer.from(encoded, "base64").toString());
  assert.deepEqual(tree.entries, entries);
  assert.equal(tree.systemPrompt, undefined);
  assert.deepEqual(html.content, [{ type: "text", text: html.details.path }]);
  assert.equal(await readFile(file, "utf8"), source);
  if (process.platform !== "win32") for (const result of [html, jsonl]) assert.equal((await stat(result.details.path)).mode & 0o777, 0o600);
  const memory = SessionManager.inMemory(cwd);
  memory.appendCustomEntry("fixture", "in-memory");
  const inMemory = await run("jsonl", memory);
  assert.notEqual(inMemory.details.path, jsonl.details.path);
  assert.match(await readFile(inMemory.details.path, "utf8"), /in-memory/);
  const before = (await readdir(cwd)).sort();
  await assert.rejects(run("html", memory), /in-memory/);
  await assert.rejects(run("jsonl", sm, AbortSignal.abort()), /abort/i);
  await rm(file);
  await assert.rejects(run("html"));
  assert.deepEqual((await readdir(cwd)).sort(), before.filter(name => name !== "input.jsonl"), "no partial export on failure");
});
